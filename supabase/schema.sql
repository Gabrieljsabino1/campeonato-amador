create table public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  nickname text not null default '',
  points integer not null default 0 check (points >= 0),
  games integer not null default 0 check (games >= 0),
  wins integer not null default 0 check (wins >= 0),
  goals integer not null default 0 check (goals >= 0),
  trend integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.posts (
  id bigint generated by default as identity primary key,
  round text not null,
  title text not null,
  excerpt text not null,
  content text not null,
  published_at timestamptz not null default now()
);

create type public.media_type as enum ('photo', 'video');
create table public.media (
  id bigint generated by default as identity primary key,
  type public.media_type not null,
  title text not null,
  url text not null,
  thumbnail text,
  date text not null default 'AGORA',
  created_at timestamptz not null default now()
);

alter table public.players enable row level security;
alter table public.posts enable row level security;
alter table public.media enable row level security;

create policy "Leitura pública de jogadores" on public.players for select using (true);
create policy "Leitura pública de resenhas" on public.posts for select using (true);
create policy "Leitura pública de mídias" on public.media for select using (true);
create policy "Admin atualiza jogadores" on public.players for update to authenticated using (true) with check (true);
create policy "Admin publica resenhas" on public.posts for insert to authenticated with check (true);
create policy "Admin publica mídias" on public.media for insert to authenticated with check (true);

-- Bucket público para fotos. Vídeos permanecem hospedados externamente.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('media', 'media', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create policy "Admin envia fotos"
on storage.objects for insert to authenticated
with check (bucket_id = 'media');

create policy "Leitura pública de fotos"
on storage.objects for select to public
using (bucket_id = 'media');

